import { describe, expect, it } from "vitest";
import { parse as parseToml } from "smol-toml";
import { parseFrontmatter } from "../src/frontmatter.js";
import { parseClaudeAgent, parseCodexAgent, renderClaudeAgent, renderCodexAgent } from "../src/render.js";
import type { CanonicalAgent } from "../src/types.js";

const agent: CanonicalAgent = {
  version: 1,
  name: "reviewer",
  description: "Reviews changes.",
  body: "Review carefully.\nA delimiter: ''' and a quote: \".\n",
  path: "/canonical/reviewer.md",
  valid: true,
  targets: {
    claude: { tools: ["Read", "Grep"], color: "cyan", model: "opus" },
    codex: {
      sandbox_mode: "read-only",
      model_reasoning_effort: "high",
      mcp_servers: { docs: { url: "https://example.test/mcp", enabled: true } },
    },
  },
};

describe("agent adapters", () => {
  it("renders deterministic Claude Markdown with ordered frontmatter", () => {
    const rendered = renderClaudeAgent(agent);
    expect(rendered).toMatchInlineSnapshot(`
      "---
      name: reviewer
      description: Reviews changes.
      color: cyan
      model: opus
      tools:
        - Read
        - Grep
      ---

      Review carefully.
      A delimiter: ''' and a quote: ".
      "
    `);
    expect(renderClaudeAgent(agent)).toBe(rendered);
    expect(parseFrontmatter(rendered, "reviewer.md").attributes).not.toHaveProperty("version");
  });

  it("renders valid deterministic Codex TOML with developer instructions last among scalars", () => {
    const rendered = renderCodexAgent(agent);
    const parsed = parseToml(rendered);
    expect(parsed).toMatchObject({
      name: "reviewer",
      description: "Reviews changes.",
      model_reasoning_effort: "high",
      sandbox_mode: "read-only",
      developer_instructions: agent.body,
      mcp_servers: { docs: { url: "https://example.test/mcp", enabled: true } },
    });
    expect(rendered.indexOf("developer_instructions")).toBeLessThan(rendered.indexOf("[mcp_servers.docs]"));
    expect(rendered).toMatch(/^# Generated by Overlord; edit the canonical \.agents definition instead\.\n/);
    expect(renderCodexAgent(agent)).toBe(rendered);
  });

  it("round-trips native Claude fields semantically", () => {
    const roundTripped = parseClaudeAgent(renderClaudeAgent(agent), "reviewer", "/native/reviewer.md");
    expect(renderClaudeAgent(roundTripped)).toBe(renderClaudeAgent(agent));
    expect(roundTripped.targets.claude).toEqual(agent.targets.claude);
  });

  it("round-trips native Codex fields semantically", () => {
    const roundTripped = parseCodexAgent(renderCodexAgent(agent), "reviewer", "/native/reviewer.toml");
    expect(renderCodexAgent(roundTripped)).toBe(renderCodexAgent(agent));
    expect(roundTripped.targets.codex).toEqual(agent.targets.codex);
  });

  it("omits disabled targets", () => {
    const claudeOnly = { ...agent, targets: { claude: {}, codex: false as const } };
    expect(() => renderCodexAgent(claudeOnly)).toThrow("disabled");
  });
});
